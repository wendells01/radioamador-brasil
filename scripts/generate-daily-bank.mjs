// Derived, reproducible study bank. Never evaluates or modifies quiz HTML/scripts.
import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {DATA} from '../site/assets/js/referencia.js';
const ROOT=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const hash=text=>createHash('sha256').update(text).digest('hex');
const normal=text=>text.normalize('NFKC').toLocaleLowerCase('pt-BR').replace(/\s+/g,' ').trim();
const clean=text=>text.replace(/^(?:Situação de prova|Questão aplicada)\s*—\s*/i,'').trim();
const referenceCodes=new RegExp(`\\b(?:${DATA.qcodes.map(q=>q.codigo).join('|')})\\b`,'i');
export function extractBank(html){
 const match=/\bconst\s+BANK\s*=\s*\[/.exec(html);
 if(!match)throw new Error('Banco de simulado ausente.');
 const start=match.index+match[0].lastIndexOf('[');
 let quoted=false,escaped=false,depth=0;
 for(let i=start;i<html.length;i++){
  const c=html[i];
  if(quoted){if(escaped)escaped=false;else if(c==='\\')escaped=true;else if(c==='"')quoted=false;continue;}
  if(c==='"'){quoted=true;continue;}
  if(c==='[')depth++;
  if(c===']'&&--depth===0){const bank=JSON.parse(html.slice(start,i+1));if(!Array.isArray(bank)||!bank.length)break;return bank;}
 }
 throw new Error('JSON do banco de simulado inválido.');
}
function topicFor(row){
 const text=normal(`${row.text} ${row.explanation}`);
 if(/ionosfer|propaga|troposfer|espor.dica|ciclo solar|onda terrestre|multipercurso|linha de visada|manchas solares/.test(text))return 'Propagação';
 if(/antena|coax|radiai|polariza|\broe\b|\bswr\b|balun|carga artificial|linha de transmiss|linha e carga|reflex.o/.test(text))return 'Antenas e cabos';
 if(/frequ.ncia|comprimento de onda|\bhertz\b|\blambda\b|faixa de|\bvhf\b|\buhf\b/.test(text)&&!/repetidor|offset|squelch|ctcss|\bdcs\b/.test(text))return 'Frequência e ondas';
 if(row.category==='Técnica e Ética Operacional'||/squelch|ctcss|\bdcs\b|offset|repetidor|\bptt\b|\bvfo\b|transceptor/.test(text))return 'HT e operação';
 if(/transistor|diodo|mosfet|\bbjt\b|amplificador|semicondut|\bdsp\b|\bsdr\b|filtro|oscilador|demodula|retifica|harm.nic|intermodula/.test(text))return 'Eletrônica';
 return 'Eletricidade';
}
export function collectExamQuestions(site=path.join(ROOT,'site')){
 const concepts=new Map(),truth=new Map();
 for(const cls of ['c','b','a']){
  const bank=extractBank(readFileSync(path.join(site,`simulados/classe-${cls}.html`),'utf8'));
  for(const row of bank){
   if(!['Técnica e Ética Operacional','Eletrônica e Eletricidade'].includes(row.category))continue;
   if(typeof row.text!=='string'||typeof row.explanation!=='string'||!row.explanation.trim()||typeof row.answer!=='boolean')throw new Error(`Questão inválida: classe ${cls}, item ${row.id}.`);
   const text=clean(row.text),key=normal(text);
   if(truth.has(key)&&truth.get(key)!==row.answer)throw new Error(`Gabaritos conflitantes para: ${text}`);
   truth.set(key,row.answer);
   // The reference already covers these subjects; do not add mirrors of them.
   if(referenceCodes.test(text)||/alfabeto|fon.tico/.test(text))continue;
   // Keep the daily technical slice independent of regulatory updates.
   if(/anatel|\bcoer\b|resoluç|licen[çc]|classe [abc]\b|autoriz[aç]/i.test(text))continue;
   const concept=normal(row.explanation);
   if(!concepts.has(concept))concepts.set(concept,[]);
   concepts.get(concept).push({...row,text,cls});
  }
 }
 const byTopic=new Map(),texts=new Set();
 for(const [concept,rows] of concepts){
  // Choose across both answer values, rather than always taking the first (true) mirror.
  const wanted=Boolean(parseInt(hash(concept).slice(0,8),16)&1);
  const row=rows.find(r=>r.answer===wanted)||rows[0],key=normal(row.text);
  if(texts.has(key))continue;texts.add(key);
  const topic=topicFor(row);
  if(!byTopic.has(topic))byTopic.set(topic,[]);
  byTopic.get(topic).push({id:`exam-${hash(concept).slice(0,16)}`,topic,question:`Julgue a afirmação: ${row.text}`,answer:row.answer?'Certo':'Errado',options:['Certo','Errado'],explanation:`Resposta: ${row.answer?'Certo':'Errado'}. ${row.explanation}`,studyUrl:`/simulados/classe-${row.cls}.html`,studyLabel:`Estudar no simulado da Classe ${row.cls.toUpperCase()}`,sourceId:row.id});
 }
 // Limit overrepresented drill families/categories; favor diverse daily subjects.
 return [...byTopic].sort(([a],[b])=>a<b?-1:1).flatMap(([,rows])=>rows.sort((a,b)=>a.id<b.id?-1:1).slice(0,48));
}
export function generatedBank(site=path.join(ROOT,'site')){
 const questions=collectExamQuestions(site);
 return '// Generated by scripts/generate-daily-bank.mjs from the original quizzes. Do not edit manually.\nexport const EXAM_QUESTIONS='+JSON.stringify(questions)+';\n';
}
export function verifyDailyBank(site){
 const file=path.join(site,'assets/js/daily-challenge-bank.js');
 if(readFileSync(file,'utf8')!==generatedBank(site))throw new Error('Banco diário desatualizado. Execute node scripts/generate-daily-bank.mjs e versione o arquivo gerado.');
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const site=path.join(ROOT,'site');
 if(process.argv.includes('--check'))verifyDailyBank(site);
 else writeFileSync(path.join(site,'assets/js/daily-challenge-bank.js'),generatedBank(site));
 const questions=collectExamQuestions(site);
 console.log(`${questions.length} questões de simulados selecionadas; `+JSON.stringify(Object.fromEntries([...new Set(questions.map(q=>q.topic))].map(topic=>[topic,questions.filter(q=>q.topic===topic).length]))));
}
